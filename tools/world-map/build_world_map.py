#!/usr/bin/env python3
"""
Builds the country outlines of the background world map (frontend/portfolio-dashboard/src/components/world-map-geo.ts).

Source: Natural Earth 1:110m admin-0 countries (public domain) as TopoJSON from the world-atlas package (ISC licence),
pinned below. Countries are keyed by ISO 3166-1 numeric code (the `id` of world-atlas); a few disputed areas without a
code are kept as land under their name. Hong Kong and Singapore are too small for 1:110m and have no polygon – the map
marks them with their exchange city only.
Projection: equirectangular, x = longitude + 180, y = TOP - latitude (degrees), Antarctica left out, coordinates rounded
to 0.1° – the browser places exchange cities and camera frames with the same formula. Standard library only.

Usage: python3 tools/world-map/build_world_map.py
"""
import json
import os
import subprocess

URL = "https://cdn.jsdelivr.net/npm/world-atlas@2.0.2/countries-110m.json"
TOP, BOTTOM = 84.0, -58.0
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "frontend", "portfolio-dashboard", "src", "components", "world-map-geo.ts")


def main():
    topo = json.loads(subprocess.run(["curl", "-sSf", "--max-time", "60", URL], check=True, capture_output=True).stdout)
    sx, sy = topo["transform"]["scale"]
    tx, ty = topo["transform"]["translate"]
    arcs = []
    for arc in topo["arcs"]:  # quantized, delta-encoded
        x = y = 0
        points = []
        for dx, dy in arc:
            x += dx
            y += dy
            points.append((x * sx + tx, y * sy + ty))
        arcs.append(points)

    def ring(indices):
        points = []
        for i in indices:
            arc = arcs[i] if i >= 0 else list(reversed(arcs[~i]))
            points.extend(arc if not points else arc[1:])
        return points

    countries = {}
    for geometry in topo["objects"]["countries"]["geometries"]:
        if geometry.get("type") not in ("Polygon", "MultiPolygon"):
            continue
        key = geometry.get("id") or geometry["properties"]["name"]
        polygons = geometry["arcs"] if geometry["type"] == "MultiPolygon" else [geometry["arcs"]]
        parts = []
        for polygon in polygons:
            for indices in polygon:
                coordinates = ring(indices)
                if max(lat for _, lat in coordinates) < BOTTOM:  # Antarctica
                    continue
                path, last = [], None
                for lon, lat in coordinates:
                    p = (round(lon + 180, 1), round(TOP - lat, 1))
                    if p != last:
                        path.append(f"{p[0]:g} {p[1]:g}")
                        last = p
                if len(path) >= 3:
                    parts.append("M" + "L".join(path) + "Z")
        if parts:
            countries[key] = "".join(parts)

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("// Generated by tools/world-map/build_world_map.py – do not edit.\n")
        f.write("// Natural Earth 1:110m countries (public domain) via world-atlas@2.0.2 (ISC); equirectangular, degrees;\n")
        f.write("// keys are ISO 3166-1 numeric codes (names for areas without one).\n")
        f.write(f"export const MAP_TOP = {TOP:g}\nexport const MAP_HEIGHT = {TOP - BOTTOM:g}\n")
        f.write("export const COUNTRY_PATHS: Record<string, string> = {\n")
        for key in sorted(countries):
            f.write(f"  {json.dumps(key)}: '{countries[key]}',\n")
        f.write("}\n")
    print(f"{OUT}: {len(countries)} countries, {os.path.getsize(OUT) // 1024} KB")


if __name__ == "__main__":
    main()
