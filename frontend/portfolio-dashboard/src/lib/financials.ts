import { compactMoney } from './fundamentals'
import { date, num, pct } from './format'
import type { FinancialRow, FinancialSection, FinancialTable, ValuationFigure } from './types'

/** Short column header of a period: "FY 2025" for a fiscal year, "Sep 2026" for the quarter ending then. */
export function periodHeader(end: string, periodType: FinancialTable['periodType']): string {
  const [y, m] = end.split('-').map(Number)
  if (periodType === 'FY') return `FY ${y}`
  const month = new Date(Date.UTC(y, m - 1, 1)).toLocaleDateString('en-US', { month: 'short', timeZone: 'UTC' })
  return `${month} ${y}`
}

/** Hover text of a period column. */
export function periodTitle(end: string, periodType: FinancialTable['periodType']): string {
  return `${periodType === 'FY' ? 'Fiscal year' : 'Fiscal quarter'} ending ${date(end)}`
}

/** A cell as text: compact amounts with currency, per-share amounts with two decimals, ratios in %, multiples with ×. */
export function financialValue(kind: FinancialRow['kind'] | ValuationFigure['kind'], value: number | null | undefined, currency: string | null): string {
  if (value === null || value === undefined || !Number.isFinite(value)) return '—'
  switch (kind) {
    case 'amount':
      return compactMoney(value, currency)
    case 'perShare':
      return currency ? `${currency} ${num(value, 2)}` : num(value, 2)
    case 'shares':
      return new Intl.NumberFormat('en-US', { notation: 'compact', maximumFractionDigits: 2 }).format(value)
    case 'ratio':
      return pct(value, 1)
    case 'multiple':
      return `${num(value, 1)}×`
  }
}

/** Indices of the periods in which at least one row of the statement has a value or a reason for none (the others would be an empty column). */
export function filledPeriods(section: FinancialSection): number[] {
  const count = section.rows[0]?.values.length ?? 0
  return Array.from({ length: count }, (_, i) => i).filter((i) => section.rows.some((r) => r.values[i] !== null || r.notes[i] !== null))
}

/** Hover text of a cell: the reason when there is no value. */
export function cellTitle(row: FinancialRow, index: number): string | undefined {
  const note = row.notes[index]
  if (note) return note
  return row.values[index] === null ? 'Not reported by the source for this period.' : undefined
}

