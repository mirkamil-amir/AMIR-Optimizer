namespace PortfolioOptimizer.Domain;

/// <summary>
/// A submitted ML research experiment: configuration (universe, model family, target, features, validation and portfolio
/// settings), lifecycle and results. Results are stored as JSON documents; models as versioned artifacts on disk.
/// </summary>
public class MlExperiment
{
    public Guid Id { get; set; }
    public Guid OwnerId { get; set; }
    public required string Name { get; set; }
    public JobStatus Status { get; set; }
    public int ProgressPercent { get; set; }
    public string? ProgressMessage { get; set; }
    public DateTime CreatedAtUtc { get; set; }
    public DateTime? StartedAtUtc { get; set; }
    public DateTime? CompletedAtUtc { get; set; }
    public string? Error { get; set; }

    public required string ModelFamily { get; set; }
    public required string Target { get; set; }
    public int HorizonDays { get; set; }
    public required string FeatureSetVersion { get; set; }
    public List<string> Symbols { get; set; } = [];
    public required string BenchmarkSymbol { get; set; }
    public required string PriceSource { get; set; }
    public bool UsesSimulatedData { get; set; }
    public DateOnly HistoryStart { get; set; }
    public DateOnly HistoryEnd { get; set; }

    /// <summary>Full request (universe, model, target, features, split, portfolio and backtest settings).</summary>
    public string ConfigJson { get; set; } = "{}";

    public string? DataSnapshotHash { get; set; }
    public DateOnly? TrainStart { get; set; }
    public DateOnly? TrainEnd { get; set; }
    public DateOnly? ValidationStart { get; set; }
    public DateOnly? ValidationEnd { get; set; }
    public DateOnly? TestStart { get; set; }
    public DateOnly? TestEnd { get; set; }
    public int TrainSamples { get; set; }
    public int ValidationSamples { get; set; }
    public int TestSamples { get; set; }
    public bool IsExploratory { get; set; }
    public double? DurationMs { get; set; }

    /// <summary>Hyperparameter search, metrics (train/validation/test), baselines, explanations.</summary>
    public string? ResultJson { get; set; }

    /// <summary>Walk-forward backtest of the ML strategy over the test period.</summary>
    public string? BacktestJson { get; set; }

    public List<string> Warnings { get; set; } = [];
    public List<MlModelVersion> ModelVersions { get; set; } = [];
}

/// <summary>
/// One trained model of an experiment. The parameters live in an artifact file (path relative to the configured artifact
/// root, generated by the server) whose SHA-256 is verified before every load.
/// </summary>
public class MlModelVersion
{
    public Guid Id { get; set; }
    public Guid ExperimentId { get; set; }
    public int Version { get; set; }

    /// <summary>"Evaluation" (trained before the test period – the source of out-of-sample metrics) or "Deployment" (all realized labels).</summary>
    public required string Role { get; set; }

    public required string ModelFamily { get; set; }
    public DateOnly TrainedFrom { get; set; }
    public DateOnly TrainedThrough { get; set; }
    public int TrainingSamples { get; set; }
    public string HyperparametersJson { get; set; } = "{}";
    public List<string> FeatureNames { get; set; } = [];
    public required string FeatureSetVersion { get; set; }
    public required string ArtifactPath { get; set; }
    public required string ArtifactSha256 { get; set; }
    public long ArtifactSizeBytes { get; set; }
    public DateTime CreatedAtUtc { get; set; }
}

/// <summary>A set of predictions for one as-of date produced by a specific model version.</summary>
public class MlPredictionSet
{
    public Guid Id { get; set; }
    public Guid ExperimentId { get; set; }
    public Guid ModelVersionId { get; set; }
    public DateOnly AsOfDate { get; set; }
    public DateTime CreatedAtUtc { get; set; }
    public int HorizonDays { get; set; }
    public double CashWeight { get; set; }
    public string? IntervalMethod { get; set; }
    public List<string> Notes { get; set; } = [];
    public bool UsesSimulatedData { get; set; }

    /// <summary>Per-stock predictions, ranks, selection, target weights and drivers.</summary>
    public string PredictionsJson { get; set; } = "[]";
}

/// <summary>
/// A saved comparison of a mathematical optimization strategy and an ML strategy (plus equal weight and the benchmark)
/// re-evaluated on one shared simulator. Immutable once completed: the stored configuration and results are never
/// recalculated with newer models or data.
/// </summary>
public class StrategyComparison
{
    public Guid Id { get; set; }
    public Guid OwnerId { get; set; }
    public required string Name { get; set; }
    public JobStatus Status { get; set; }
    public int ProgressPercent { get; set; }
    public string? ProgressMessage { get; set; }
    public DateTime CreatedAtUtc { get; set; }
    public DateTime? StartedAtUtc { get; set; }
    public DateTime? CompletedAtUtc { get; set; }
    public string? Error { get; set; }

    /// <summary>Referenced optimization run (null if it was deleted later; its settings are copied into the configuration).</summary>
    public Guid? OptimizationRunId { get; set; }

    /// <summary>Referenced ML experiment (null if deleted later; its configuration and hyperparameters are copied).</summary>
    public Guid? MlExperimentId { get; set; }

    /// <summary>Model version whose selected hyperparameters were used for the walk-forward ML strategy.</summary>
    public Guid? MlModelVersionId { get; set; }

    public DateOnly EvaluationStart { get; set; }
    public DateOnly EvaluationEnd { get; set; }
    public required string BenchmarkSymbol { get; set; }
    public required string PriceSource { get; set; }
    public bool UsesSimulatedData { get; set; }
    public string? DataSnapshotHash { get; set; }
    public bool? IsFair { get; set; }

    /// <summary>Request plus the resolved snapshots of both strategies' settings.</summary>
    public string ConfigJson { get; set; } = "{}";

    /// <summary>Series, metrics, allocations, overlap, fairness assessment.</summary>
    public string? ResultJson { get; set; }

    public List<string> Warnings { get; set; } = [];
}
